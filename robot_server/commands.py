"""
Распознавание голосовых команд для управления роботом.
Простой keyword-matching по русским словам.
"""
import logging

log = logging.getLogger(__name__)

# Словарь: ключевые слова → команда
_RULES = [
    # Движение
    (["вперёд", "вперед", "езжай", "двигайся"],            "move_forward"),
    (["назад", "задний"],                                   "move_backward"),
    (["влево", "налево", "поверни влево"],                  "move_left"),
    (["вправо", "направо", "поверни вправо"],               "move_right"),
    (["повернись", "вращение"],                             "rotate"),
    (["стоп", "остановись", "стой", "стоять", "хватит"],   "stop"),

    # Захват
    (["возьми", "захвати", "схвати", "бери"],               "grab"),
    (["отпусти", "положи", "брось", "выпусти"],             "release"),

    # Рука
    (["домой", "исходное", "нейтральное"],                  "arm_home"),
    (["подними", "вверх"],                                  "arm_up"),
    (["опусти", "вниз"],                                    "arm_down"),

    # Статус
    (["батарея", "заряд"],                                  "status_battery"),
    (["расстояние", "сонар", "препятствие"],                "status_sonar"),
]


def parse(text: str) -> str | None:
    """
    Возвращает название команды или None если не распознано.
    """
    text = text.lower().strip()
    for keywords, command in _RULES:
        for kw in keywords:
            if kw in text:
                log.info(f"Команда: '{text}' → {command}")
                return command
    log.debug(f"Команда не распознана: '{text}'")
    return None
